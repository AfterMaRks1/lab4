if __name__ == "__main__":
    print("Введите стоимость товаров для первого магазина за июль:")
    магазин1_июль = list(map(float, input().split()))

    print("Введите стоимость товаров для первого магазина за август:")
    магазин1_август = list(map(float, input().split()))

    print("Введите стоимость товаров для второго магазина за июль:")
    магазин2_июль = list(map(float, input().split()))

    print("Введите стоимость товаров для второго магазина за август:")
    магазин2_август = list(map(float, input().split()))

    # Проверка: все массивы должны быть одного размера
    if not (
        len(магазин1_июль)
        == len(магазин1_август)
        == len(магазин2_июль)
        == len(магазин2_август)
    ):
        print("Ошибка: количество дней в массивах не совпадает!")
        exit(1)

    общая_стоимость = 0

    # Суммируем все элементы всех массивов
    for день in range(len(магазин1_июль)):
        общая_стоимость += магазин1_июль[день]
        общая_стоимость += магазин1_август[день]
        общая_стоимость += магазин2_июль[день]
        общая_стоимость += магазин2_август[день]

    print(f"Общая стоимость товаров за два месяца: {общая_стоимость:.2f}")
