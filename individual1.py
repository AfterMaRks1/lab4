import sys

if __name__ == "__main__":
    # Ввести список одной строкой
    A = list(map(int, input().split()))
    # Проверить количество элементов
    if len(A) != 10:
        print("Неверный размер списка", file=sys.stderr)
        exit(1)
    # Найти положительные элементы, кратные 11
    числа = []
    for item in A:
        if item > 0 and item % 11 == 0:
            числа.append(item)
    # Вывести результаты
    if not числа:
        print("Положительных элементов, кратных 11, нет")
    else:
        количество = len(числа)
        разность = max(числа) - min(числа)
        print(f"Количество: {количество}")
        print(f"Разность: {разность}")
